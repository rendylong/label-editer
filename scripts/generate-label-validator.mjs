import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import { _ } from 'ajv/dist/compile/codegen/index.js'
import standaloneCode from 'ajv/dist/standalone/index.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const schemaPath = path.join(root, 'src/agent/label-spec-v2.schema.json')
const outputPath = path.join(root, 'src/agent/generated/labelSpecV2Validator.ts')
const schema = JSON.parse(await readFile(schemaPath, 'utf8'))
const designOutputPath = path.join(root, 'src/agent/generated/designContractValidators.ts')

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { source: true, esm: true, lines: true },
})
const runtimeImports = [
  ['ajv/dist/runtime/ucs2length', 'import $name from "ajv/dist/runtime/ucs2length";'],
  ['ajv/dist/runtime/equal', 'import $name from "ajv/dist/runtime/equal";'],
]
function esmStandalone(source) {
  let generated = source.replace('"use strict";\n', '')
  for (const [moduleName, replacement] of runtimeImports) {
    generated = generated.replace(
      new RegExp(`const (func\\d+) = require\\("${moduleName}"\\)\\.default;`, 'g'),
      (_match, name) => replacement.replace('$name', name),
    )
  }
  if (generated.includes('require(')) {
    throw new Error('Generated validator contains an unresolved CommonJS runtime import')
  }
  return generated
}

const generated = esmStandalone(standaloneCode(ajv, ajv.compile(schema)))

await mkdir(path.dirname(outputPath), { recursive: true })
await writeFile(
  outputPath,
  `// Generated by scripts/generate-label-validator.mjs. Do not edit.\n// @ts-nocheck\n${generated}`,
)

const designSchemaFiles = {
  validateBlueprintSchema: 'layout-blueprint-v1.schema.json',
  validateHandoffSchema: 'editor-handoff-v2.schema.json',
  validateApprovalSchema: 'approval-record-v1.schema.json',
  validateDesignManifestSchema: 'design-review-manifest-v1.schema.json',
  validateProductionManifestSchema: 'review-manifest-v1.schema.json',
  validateWorkflowProjectSchema: 'label-project-v3.schema.json',
}
const designAjv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { source: true, esm: true, lines: true, formats: _`strictFormats` },
})
designAjv.addFormat('date-time', { type: 'string', validate: () => true })
const designExports = {}
for (const [exportName, fileName] of Object.entries(designSchemaFiles)) {
  const value = JSON.parse(await readFile(path.join(root, 'src/agent', fileName), 'utf8'))
  designAjv.addSchema(value)
  designExports[exportName] = value.$id
}
const designGenerated = esmStandalone(standaloneCode(designAjv, designExports))
await writeFile(
  designOutputPath,
  `// Generated by scripts/generate-label-validator.mjs. Do not edit.\n// @ts-nocheck\nimport { isStrictRfc3339DateTime } from '../../../scripts/lib/design-manifest-core.mjs'\nconst strictFormats = { 'date-time': { type: 'string', validate: isStrictRfc3339DateTime } }\n${designGenerated}`,
)
