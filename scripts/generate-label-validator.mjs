import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const schemaPath = path.join(root, 'src/agent/label-spec-v2.schema.json')
const outputPath = path.join(root, 'src/agent/generated/labelSpecV2Validator.ts')
const schema = JSON.parse(await readFile(schemaPath, 'utf8'))

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { source: true, esm: true, lines: true },
})
const generated = standaloneCode(ajv, ajv.compile(schema))
  .replace('"use strict";\n', '')
  .replace(
    'const func1 = require("ajv/dist/runtime/ucs2length").default;',
    'import func1 from "ajv/dist/runtime/ucs2length";',
  )
  .replace(
    'const func0 = require("ajv/dist/runtime/equal").default;',
    'import func0 from "ajv/dist/runtime/equal";',
  )

await mkdir(path.dirname(outputPath), { recursive: true })
await writeFile(
  outputPath,
  `// Generated by scripts/generate-label-validator.mjs. Do not edit.\n// @ts-nocheck\n${generated}`,
)
